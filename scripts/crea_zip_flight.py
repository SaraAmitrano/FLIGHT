def main():
    directory = Path(sys.argv[1] if len(sys.argv) > 1 else ".").expanduser().resolve()
    output = (
        Path(sys.argv[2] if len(sys.argv) > 2 else "FLIGHT_analisi.zip")
        .expanduser()
        .resolve()
    )
    if not directory.is_dir():
        sys.exit(f"Errore: cartella FLIGHT non trovata: {directory}")
    included = []
    missing = []
    with ZipFile(output, "w", compression=ZIP_DEFLATED, compresslevel=9) as archive:
        for relative in FILES:
            file = directory / relative
            if file.is_file() and not file.is_symlink():
                archive.write(file, arcname=f"FLIGHT/{relative}")
                included.append(relative)
            else:
                missing.append(relative)
    print(f"Creato: {output}")
    print(f"File inclusi: {len(included)}")
    if missing:
        print(f"File non trovati (omessi): {len(missing)}")
        for name in missing:
            print(f"  - {name}")


if __name__ == "__main__":
    main()
